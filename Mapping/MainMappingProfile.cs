using AutoMapper;
using HelpDesk.Data.Dto;
using HelpDesk.Data.Models;

namespace HelpDesk.Mapping
{
    public class MainMappingProfile : Profile
    {
        public MainMappingProfile()
        {
            // ---------- Entity -> DTO (output) ----------
            CreateMap<User, UserDto>();
            CreateMap<Ticket, TicketDto>();
            CreateMap<Message, MessageDto>();
            CreateMap<Attachment, AttachmentDto>();

            // ---------- DTO -> Entity (input) ----------

            // PassHash is produced by your password hasher in the service layer,
            // never mapped from the plain-text Password.
            CreateMap<CreateUserDto, User>()
                .ForMember(d => d.Id, o => o.Ignore())          // generated by the app/DB
                .ForMember(d => d.PassHash, o => o.MapFrom(src => src.Password))
                .ForMember(d => d.Role, o => o.Ignore())        // keeps the "User" default
                .ForMember(d => d.Tickets, o => o.Ignore());

            CreateMap<UpdateUserDto, User>()
                .ForMember(d => d.Id, o => o.Ignore())
                .ForMember(d => d.PassHash, o => o.MapFrom(src => src.Password))
                .ForMember(d => d.Role, o => o.Ignore())
                .ForMember(d => d.Tickets, o => o.Ignore());

            CreateMap<TicketDto, Ticket>()
                .ForMember(d => d.Id, o => o.Ignore())
                .ForMember(d => d.CreatedAt, o => o.Ignore())   // server-controlled
                .ForMember(d => d.User, o => o.Ignore());

            CreateMap<MessageDto, Message>()
                .ForMember(d => d.Id, o => o.Ignore())
                .ForMember(d => d.CreatedAt, o => o.Ignore())   // server-controlled
                .ForMember(d => d.TicketId, o => o.Ignore())
                .ForMember(d => d.Ticket, o => o.Ignore());

            // Attachment rows are created by the upload flow, which fills in StoragePath.
            CreateMap<AttachmentDto, Attachment>()
                .ForMember(d => d.Id, o => o.Ignore())
                .ForMember(d => d.CreatedAt, o => o.Ignore())   // server-controlled
                .ForMember(d => d.StoragePath, o => o.Ignore())
                .ForMember(d => d.TicketId, o => o.Ignore())
                .ForMember(d => d.Ticket, o => o.Ignore());
        }
    }
}