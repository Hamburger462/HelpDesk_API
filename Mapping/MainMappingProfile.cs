using AutoMapper;
using HelpDesk.Data.Dto;
using HelpDesk.Data.Models;
using HelpDesk.Features.Auth.Register;

namespace HelpDesk.Mapping
{
    public class MainMappingProfile : Profile
    {
        public MainMappingProfile()
        {
            // ---------- Entity -> DTO (output) ----------
            CreateMap<User, UserSummaryDto>();

            CreateMap<User, UserDto>()
                .ForMember(d => d.Tickets, o => o.MapFrom(s => s.CreatedTickets));

            // Assignees (List<User>) -> List<UserSummaryDto> uses the summary map above.
            // CreatedById is copied by convention.
            CreateMap<Ticket, TicketDto>();

            // AuthorFullName / UploadedByFullName are flattened from Author.FullName / UploadedBy.FullName.
            CreateMap<Message, MessageDto>();
            CreateMap<Attachment, AttachmentDto>();

            // ---------- DTO -> Entity (input) ----------

            // PassHash is mapped from the plain-text Password here, so the handlers must hash it
            // before SaveChanges.
            CreateMap<CreateUserDto, User>()
                .ForMember(d => d.Id, o => o.Ignore())              // generated by the app/DB
                .ForMember(d => d.PassHash, o => o.MapFrom(src => src.Password))
                .ForMember(d => d.Role, o => o.Ignore())            // keeps the "User" default
                .ForMember(d => d.CreatedTickets, o => o.Ignore())
                .ForMember(d => d.AssignedTickets, o => o.Ignore());

            CreateMap<UpdateUserDto, User>()
                .ForMember(d => d.Id, o => o.Ignore())
                .ForMember(d => d.PassHash, o => o.MapFrom(src => src.Password))
                .ForMember(d => d.Role, o => o.Ignore())
                .ForMember(d => d.CreatedTickets, o => o.Ignore())
                .ForMember(d => d.AssignedTickets, o => o.Ignore());

            CreateMap<RegisterDto, CreateUserDto>();

            // Only Title, Urgency and the initial messages come from the client.
            // The handler sets CreatedById (from the authenticated user) and the author of each initial message.
            // Status changes and assignment go through their own endpoints.
            CreateMap<TicketDto, Ticket>()
                .ForMember(d => d.Id, o => o.Ignore())
                .ForMember(d => d.Status, o => o.Ignore())          // starts as Open
                .ForMember(d => d.CreatedAt, o => o.Ignore())       // server-controlled
                .ForMember(d => d.UpdatedAt, o => o.Ignore())
                .ForMember(d => d.ResolvedAt, o => o.Ignore())
                .ForMember(d => d.CreatedById, o => o.Ignore())
                .ForMember(d => d.CreatedBy, o => o.Ignore())
                .ForMember(d => d.Assignees, o => o.Ignore())
                .ForMember(d => d.Attachments, o => o.Ignore());    // files only come from the upload endpoint

            // The handler sets AuthorId (authenticated user) and TicketId (route).
            CreateMap<MessageDto, Message>()
                .ForMember(d => d.Id, o => o.Ignore())
                .ForMember(d => d.CreatedAt, o => o.Ignore())       // server-controlled
                .ForMember(d => d.AuthorId, o => o.Ignore())
                .ForMember(d => d.Author, o => o.Ignore())
                .ForMember(d => d.TicketId, o => o.Ignore())
                .ForMember(d => d.Ticket, o => o.Ignore());

            // Attachment rows are created by the upload flow, which fills in StoragePath and UploadedById.
            CreateMap<AttachmentDto, Attachment>()
                .ForMember(d => d.Id, o => o.Ignore())
                .ForMember(d => d.CreatedAt, o => o.Ignore())       // server-controlled
                .ForMember(d => d.StoragePath, o => o.Ignore())
                .ForMember(d => d.UploadedById, o => o.Ignore())
                .ForMember(d => d.UploadedBy, o => o.Ignore())
                .ForMember(d => d.TicketId, o => o.Ignore())
                .ForMember(d => d.Ticket, o => o.Ignore());
        }
    }
}
